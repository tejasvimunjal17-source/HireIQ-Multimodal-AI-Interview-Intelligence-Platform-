import type { InterviewSummary } from "./interview";

// These shapes mirror the FastAPI schemas in backend/app/schemas/dashboard.py (Day 7).

export type Advice = "proceed" | "hold" | "reject";
export type SessionStatusValue = "created" | "in_progress" | "submitted" | "processing" | "evaluated" | "failed";

export interface AdviceCounts { proceed: number; hold: number; reject: number }

export interface SessionRow {
  session_id: string;
  candidate_name: string | null;
  interview_id: string;
  interview_title: string;
  interview_date: string | null;
  status: string;
  question_count: number;
  answered_count: number;
  evaluated_count: number;
  /** 0-100, or null when nothing is scored. null is NOT zero. */
  overall_score: number | null;
  score_source: "stored_report" | "average_of_answers" | null;
  /** Stored session-level recommendation (usually null). */
  recommendation: Advice | null;
  advice: AdviceCounts;
}

export interface SessionPage { items: SessionRow[]; total: number; page: number; page_size: number }

export interface ScoreBucket { label: string; min: number; max: number; count: number }

export interface DashboardSummary {
  total_sessions: number;
  by_status: Record<string, number>;
  completed_interviews: number;
  awaiting_evaluation: number;
  evaluation_failed: number;
  evaluated_sessions: number;
  scored_sessions: number;
  average_score: number | null;
  score_distribution: ScoreBucket[];
}

export interface CriterionView {
  key: string;
  score: number;
  weight: number | null;
  explanation: string;
  evidence_quotes: string[];
}

export interface NlpInsights {
  status?: string;
  word_count?: number | null;
  keywords?: { text: string; count: number }[];
  entities?: { text: string; label: string; count: number }[];
  sentiment?: { label: string; positive: number; neutral: number; negative: number; compound: number } | null;
  confidence?: { score: number | null; label: string | null; disclaimer?: string } | null;
}

export interface AnswerView {
  position: number;
  question: string;
  status_text: string;
  overall_score: number | null;
  recommendation: Advice | null;
  summary: string;
  strengths: string[];
  improvements: string[];
  criteria: CriterionView[];
  scale_min: number | null;
  scale_max: number | null;
  nlp: NlpInsights | null;
}

export interface CriteriaSummary {
  points: { key: string; value: number; answers: number }[];
  scale_min: number | null;
  scale_max: number | null;
  unavailable_reason: string;
}

export interface SessionDetail {
  session_id: string;
  candidate_name: string | null;
  interview_title: string | null;
  interview_date: string | null;
  status: string;
  question_count: number;
  evaluated_count: number;
  is_complete: boolean;
  overall_score: number | null;
  score_source: "stored_report" | "average_of_answers" | null;
  recommendation: Advice | null;
  answers: AnswerView[];
  criteria_summary: CriteriaSummary;
}

export interface SessionFilters {
  search: string;
  interviewId: string;
  status: string;
  recommendation: string;
  page: number;
}

export const PAGE_SIZE = 20;

/** Everything the dashboard needs from a backend. The access token lives inside the implementation, never in a component. */
export interface DashboardApi {
  /** The existing public GET /api/interviews (used for the role filter). */
  listInterviews(): Promise<InterviewSummary[]>;
  getSummary(): Promise<DashboardSummary>;
  listSessions(filters: SessionFilters): Promise<SessionPage>;
  getSessionDetail(sessionId: string): Promise<SessionDetail>;
  /** The PDF generated by the existing backend endpoint (no PDF logic in the browser). */
  downloadReport(sessionId: string): Promise<Blob>;
}
